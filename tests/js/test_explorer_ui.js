/* DOM integration checks; npm install --no-save jsdom js-yaml@4.1.0 marked@12.0.2 d3@7.9.0 dompurify@3.3.1 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root,p), 'utf8');
const dom = new JSDOM(read('site/explorador/index.html'), {url:'https://example.org/explorador/',runScripts:'outside-only',pretendToBeVisual:true});
const w = dom.window;
w.matchMedia = () => ({matches:false,addEventListener(){}});
w.ResizeObserver = class {observe(){}};
w.CSS = {escape:s=>s.replace(/[^a-zA-Z0-9_-]/g,c=>'\\'+c)};
w.HTMLElement.prototype.scrollIntoView = function(){};
w.SVGElement.prototype.getBBox = () => ({x:0,y:0,width:800,height:500});
for (const key of ['width','height']) Object.defineProperty(w.SVGElement.prototype,key,{get:()=>({baseVal:{value:800}})});
Object.defineProperty(w.SVGElement.prototype,'viewBox',{get:()=>({baseVal:{x:0,y:0,width:800,height:500}})});
w.MathJax = {typesetPromise:async()=>{}};
w.mermaid = {render:async()=>({svg:'<svg></svg>'})};
w.eval(fs.readFileSync(path.join(path.dirname(require.resolve('d3')), '../dist/d3.min.js'),'utf8'));
w.marked = require('marked');
w.jsyaml = require('js-yaml');
w.DOMPurify = require('dompurify')(w);
const vault = JSON.parse(read('site/explorador/vault.json'));
w.fetch = async()=>({ok:true,json:async()=>vault});
w.eval(read('explorer/vault-parser.js'));
w.eval(read('explorer/app.js'));
(async()=>{
 await new Promise(r=>setTimeout(r,100));
 const $ = s=>w.document.querySelector(s);
 assert.ok($('#vault-meta').textContent.includes(String(vault.files.length)));
 assert.ok(w.document.querySelectorAll('#list .item').length>40);
 const chapter = w.document.querySelector('#list [data-note="part-02-classical-reserving/06-chain-ladder-method.md"]');
 chapter.click();
 assert.match($('#note').textContent,/Chain Ladder/);
 assert.ok(w.document.querySelectorAll('#note .kb-math').length>0);
 assert.ok($('#note .int[data-note]'));
 $('#tab-local').click();
 assert.equal($('#tab-local').getAttribute('aria-selected'),'true');
 $('#q').value='Mack'; $('#q').dispatchEvent(new w.Event('input'));
 await new Promise(r=>setTimeout(r,250));
 assert.ok($('#q-count').textContent);
 $('#ui-lang').click(); assert.equal(w.document.documentElement.lang,'en');
 $('#theme-toggle').click(); assert.equal(w.document.documentElement.dataset.theme,'dark');
 const clean=w.DOMPurify.sanitize('<img src=x onerror="window.pwned=1"><a href="java&#10;script:alert(1)">x</a><svg onload="alert(1)"></svg>',{USE_PROFILES:{html:true}});
 assert.ok(!/onerror|javascript|onload|<svg/i.test(clean));
 console.log('Explorer DOM checks passed: loading, navigation, math markup, links, local graph, search, language, theme, sanitizer.');
 dom.window.close();
})().catch(e=>{console.error(e);dom.window.close();process.exitCode=1;});
